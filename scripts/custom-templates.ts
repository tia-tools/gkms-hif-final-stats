/**
 * Writes `src/reader/custom-templates.ts`: the カスタム P-item's character and accessory layers
 * (decision G33) as small templates, the only form of that art this repository keeps (G37). Each
 * is the layer's mean colour over its opaque pixels, and how much of it is opaque, on a 16 × 16
 * grid.
 *
 * The layers come from the game's asset bundles, extracted with the GkmasObjectManager checkout
 * that gakumas-supportcards vendors (`docs/plans/EXECPLAN_HIF_FINAL_STATS.md` § Concrete Steps).
 * Pass the folder of the extracted 1024 × 1024 PNGs, named
 * `img_general_cstm-pitem_04-2-00N.unity3d.png`, and the manifest version they came from:
 *
 *     bun scripts/custom-templates.ts <folder> <manifest version>
 *
 * The layer art is not committed (G37), so no test can regenerate these templates. Instead the
 * file records the manifest and each layer's SHA-256: templates cut from other art show in the diff.
 */

import { iconTemplate } from "../src/reader/items.ts";
import { decodePng } from "../src/test-support/png.ts";

/** Fine enough for the メダル, the smallest accessory. */
const CELLS = 16;

const LAYERS = {
  characters: { くま: "04-2-001", 人形: "04-2-002", ロボ: "04-2-003", もじゃ: "04-2-004", インコ: "04-2-005", うさぎ: "04-2-006" },
  accessories: { 花: "04-4-001", リボン: "04-4-002", メダル: "04-4-003", 羽: "04-4-004" },
};

const [folder, manifest] = process.argv.slice(2);
if (folder === undefined || manifest === undefined) throw new Error("usage: bun scripts/custom-templates.ts <folder of extracted layers> <manifest version>");

/** R, G and B as two hex digits each; the opaque share as one, in fifteenths. */
const rgbHex = (values: Float32Array) => Array.from(values, (v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, "0")).join("");
const coverHex = (values: Float32Array) => Array.from(values, (v) => Math.round(Math.min(1, Math.max(0, v)) * 15).toString(16)).join("");

let text = "// Generated by scripts/custom-templates.ts from the カスタム item's layers; do not edit.\n";
text += `// Per layer, on a ${CELLS} × ${CELLS} grid, row by row: R, G and B over the opaque pixels (two hex digits each) and the opaque share (one, in fifteenths).\n\n`;
text += `// From the game's asset manifest ${manifest}; each layer's source is the first 16 hex digits of its PNG's SHA-256.\n\n`;
text += `export const LAYER_CELLS = ${CELLS};\n\nexport const STORED_LAYERS = {\n`;
for (const [group, layers] of Object.entries(LAYERS)) {
  text += `  ${group}: {\n`;
  for (const [name, asset] of Object.entries(layers)) {
    const bytes = await Bun.file(`${folder}/img_general_cstm-pitem_${asset}.unity3d.png`).bytes();
    const source = new Bun.CryptoHasher("sha256").update(bytes).digest("hex").slice(0, 16);
    const t = iconTemplate(decodePng(bytes), CELLS, 2);
    text += `    ${name}: { asset: "${asset}", source: "${source}", rgb: "${rgbHex(t.rgb)}", cover: "${coverHex(t.cover)}" },\n`;
  }
  text += "  },\n";
}
text += "} as const;\n";
await Bun.write(new URL("../src/reader/custom-templates.ts", import.meta.url), text);
console.log("wrote src/reader/custom-templates.ts");
